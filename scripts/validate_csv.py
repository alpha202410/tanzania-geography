#!/usr/bin/env python3
"""Validate the region CSVs in location-files/ before they are imported.

Exits non-zero if it finds a problem that is not listed in the baseline file
(scripts/known-data-issues.txt). The baseline records issues already in the data,
so CI blocks new problems while those are fixed. Run with --write-baseline to
regenerate it after fixing data. Checks:
- UTF-8 without a BOM, LF line endings, a header row and exactly 8 columns per row;
- region, regioncode, district, districtcode, ward and wardcode are present;
- codes are numeric, a ward code starts with its district code, and a district code starts with its region
  code (2-digit district codes are exempt: Dar es Salaam's districts are their own zones);
- every code always carries the same name;
- each file holds a single region;
- no leading or trailing spaces and no duplicate rows.
"""
import csv
import glob
import os
import sys
from collections import defaultdict

ARGS = [a for a in sys.argv[1:] if not a.startswith("--")]
WRITE_BASELINE = "--write-baseline" in sys.argv
DATA_DIR = ARGS[0] if ARGS else "location-files"
BASELINE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "known-data-issues.txt")
COLUMNS = 8
problems: list[tuple[str, str]] = []
names: dict[str, dict[str, set[str]]] = {"region": defaultdict(set), "district": defaultdict(set), "ward": defaultdict(set)}
seen_rows: dict[tuple, str] = {}


def problem(where: str, msg: str, key: str | None = None) -> None:
    """Record a problem. `key` identifies it by content, so the baseline survives line moves."""
    problems.append((key or f"{where}|{msg}", f"{where}: {msg}"))


files = sorted(glob.glob(os.path.join(DATA_DIR, "*.csv")))
if not files:
    print(f"no CSV files in {DATA_DIR}")
    sys.exit(1)

for path in files:
    name = os.path.basename(path)
    raw = open(path, "rb").read()
    if raw.startswith(b"\xef\xbb\xbf"):
        problem(name, "starts with a UTF-8 BOM")
    if b"\r" in raw:
        problem(name, "has CR characters (CRLF line endings)")
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as e:
        problem(name, f"is not valid UTF-8 ({e})")
        continue
    rows = list(csv.reader(text.splitlines()))
    if not rows:
        problem(name, "is empty")
        continue
    regions_in_file = set()
    for i, row in enumerate(rows[1:], start=2):
        where = f"{name}:{i}"
        rowkey = f"{name}|{','.join(row)}"
        if len(row) != COLUMNS:
            problem(where, f"has {len(row)} columns, expected {COLUMNS}", f"{rowkey}|columns")
            continue
        region, rcode, district, dcode, ward, wcode, street, place = row
        for label, value in (("region", region), ("regioncode", rcode), ("district", district),
                             ("districtcode", dcode), ("ward", ward), ("wardcode", wcode)):
            if not value.strip():
                problem(where, f"{label} is empty", f"{rowkey}|empty {label}")
        for label, value in zip(("region", "regioncode", "district", "districtcode", "ward", "wardcode", "street", "places"), row):
            if value != value.strip():
                problem(where, f"{label} has leading or trailing spaces: {value!r}", f"{rowkey}|spaces {label}")
        if not (rcode.strip().isdigit() and dcode.strip().isdigit() and wcode.strip().isdigit()):
            problem(where, f"non-numeric code: {rcode!r}/{dcode!r}/{wcode!r}", f"{rowkey}|non-numeric")
            continue
        rc, dc, wc = rcode.strip(), dcode.strip(), wcode.strip()
        if len(dc) > 2 and not dc.startswith(rc):
            problem(where, f"district code {dc} does not start with region code {rc}", f"{rowkey}|district prefix")
        if not wc.startswith(dc):
            problem(where, f"ward code {wc} does not start with district code {dc}", f"{rowkey}|ward prefix")
        names["region"][rc].add(region.strip())
        names["district"][dc].add(district.strip())
        names["ward"][wc].add(ward.strip())
        regions_in_file.add(rc)
        key = tuple(v.strip() for v in row)
        if key in seen_rows:
            problem(where, f"duplicate of {seen_rows[key]}", f"{rowkey}|duplicate")
        else:
            seen_rows[key] = where
    if len(regions_in_file) > 1:
        problem(name, f"holds more than one region code: {sorted(regions_in_file)}", f"{name}|regions {sorted(regions_in_file)}")

for level, by_code in names.items():
    for code, ns in sorted(by_code.items()):
        if len(ns) > 1:
            problem(f"{level} {code}", f"has more than one name: {sorted(ns)}", f"{level} {code}|names {sorted(ns)}")

keys = sorted({k for k, _ in problems})
if WRITE_BASELINE:
    with open(BASELINE, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# Known data issues, one per line. Generated by validate_csv.py --write-baseline.\n")
        fh.write("# Fix the data, then regenerate. CI fails on any problem NOT listed here.\n")
        fh.writelines(k + "\n" for k in keys)
    print(f"wrote {len(keys)} known issue(s) to {BASELINE}")
    sys.exit(0)

known = set()
if os.path.exists(BASELINE):
    with open(BASELINE, encoding="utf-8") as fh:
        known = {line.rstrip("\n") for line in fh if line.strip() and not line.startswith("#")}
new = [(k, msg) for k, msg in problems if k not in known]
fixed = known - set(keys)
print(f"{len(files)} files, {len(seen_rows)} rows, {len(keys)} known issue(s) still present")
if fixed:
    print(f"{len(fixed)} baseline issue(s) are fixed: regenerate the baseline with --write-baseline")
if new:
    for _, msg in new:
        print(f"NEW: {msg}")
    print(f"\n{len(new)} new problem(s)")
    sys.exit(1)
print("ok: no new problems")
